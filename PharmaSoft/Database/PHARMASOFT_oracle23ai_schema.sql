    CONSTRAINT fk_pm_promotions FOREIGN KEY (promotion_id) REFERENCES promotions(promotion_id),
    CONSTRAINT fk_pm_medicines  FOREIGN KEY (medicine_id)  REFERENCES medicines(medicine_id)
);

