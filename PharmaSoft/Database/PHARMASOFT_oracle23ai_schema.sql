CREATE TABLE orders (                                           -- gộp bán tại quầy (POS) và đơn online
    order_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    invoice_code     VARCHAR2(40 CHAR) NOT NULL CONSTRAINT uq_orders_invoice UNIQUE,
    channel          VARCHAR2(10 CHAR) DEFAULT 'POS' NOT NULL CONSTRAINT ck_orders_channel CHECK (channel IN ('POS','ONLINE')),
    customer_id      NUMBER,
    created_by       NUMBER,
    promotion_id     NUMBER,
    prescription_id  NUMBER,
    order_date       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    subtotal         NUMBER(18,2) DEFAULT 0 NOT NULL,
    discount_amount  NUMBER(18,2) DEFAULT 0 NOT NULL,
    shipping_fee     NUMBER(18,2) DEFAULT 0 NOT NULL,
    total_amount     NUMBER(18,2) DEFAULT 0 NOT NULL,
    order_status     VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL
        CONSTRAINT ck_orders_status CHECK (order_status IN ('PENDING','CONFIRMED','SHIPPING','COMPLETED','CANCELLED','RETURNED')),
    payment_status   VARCHAR2(20 CHAR) DEFAULT 'UNPAID' NOT NULL
        CONSTRAINT ck_orders_pay CHECK (payment_status IN ('UNPAID','PAID','REFUNDED')),
    shipping_address JSON,                                      -- {"receiver":"..","phone":"..","street":"..","district":".."}
    note             VARCHAR2(500 CHAR),
    CONSTRAINT fk_orders_customers    FOREIGN KEY (customer_id)     REFERENCES customers(customer_id),
    CONSTRAINT fk_orders_users        FOREIGN KEY (created_by)      REFERENCES users(user_id),
    CONSTRAINT fk_orders_promotions   FOREIGN KEY (promotion_id)    REFERENCES promotions(promotion_id),
    CONSTRAINT fk_orders_prescription FOREIGN KEY (prescription_id) REFERENCES prescriptions(prescription_id),
    CONSTRAINT ck_orders_amounts CHECK (subtotal >= 0 AND discount_amount >= 0 AND shipping_fee >= 0 AND total_amount >= 0),
    CONSTRAINT ck_orders_total   CHECK (total_amount = subtotal - discount_amount + shipping_fee)
);
CREATE INDEX ix_orders_date     ON orders(order_date);
CREATE INDEX ix_orders_customer ON orders(customer_id);

CREATE TABLE order_items (
    order_item_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    order_id      NUMBER NOT NULL,
    medicine_id   NUMBER NOT NULL,
    batch_id      NUMBER,                                       -- lô đã xuất (FEFO)
    quantity      NUMBER(10) NOT NULL CONSTRAINT ck_oi_qty   CHECK (quantity > 0),
    unit_price    NUMBER(18,2) NOT NULL CONSTRAINT ck_oi_price CHECK (unit_price >= 0),  -- giá chốt lúc bán
    unit_cost     NUMBER(18,2) DEFAULT 0 NOT NULL,              -- để tính lợi nhuận
    CONSTRAINT fk_oi_orders    FOREIGN KEY (order_id)    REFERENCES orders(order_id),
    CONSTRAINT fk_oi_medicines FOREIGN KEY (medicine_id) REFERENCES medicines(medicine_id),
    CONSTRAINT fk_oi_batches   FOREIGN KEY (batch_id)    REFERENCES medicine_batches(batch_id)
);
CREATE INDEX ix_oi_order    ON order_items(order_id);
CREATE INDEX ix_oi_medicine ON order_items(medicine_id);

CREATE TABLE payments (
    payment_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
