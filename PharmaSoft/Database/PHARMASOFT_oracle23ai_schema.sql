-- 3.4 Đơn hàng / hóa đơn: 1 document gồm khách + các dòng hàng + thanh toán
CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW order_dv AS
SELECT JSON {
    '_id'            : o.order_id,
    'invoiceCode'    : o.invoice_code,
    'channel'        : o.channel,
    'orderDate'      : o.order_date,
    'subtotal'       : o.subtotal,
    'discountAmount' : o.discount_amount,
    'shippingFee'    : o.shipping_fee,
    'totalAmount'    : o.total_amount,
    'orderStatus'    : o.order_status,
    'paymentStatus'  : o.payment_status,
    'shippingAddress': o.shipping_address,
    'note'           : o.note,
    'customer'       : (SELECT JSON {'customerId': c.customer_id, 'fullName': c.full_name, 'phone': c.phone}
                        FROM customers c WHERE c.customer_id = o.customer_id
                        WITH NOINSERT NOUPDATE NODELETE),
    'items'          : [ SELECT JSON {'orderItemId': i.order_item_id,
                                      'quantity'   : i.quantity,
                                      'unitPrice'  : i.unit_price,
                                      'unitCost'   : i.unit_cost,
                                      'medicine'   : (SELECT JSON {'medicineId': m.medicine_id,
                                                                   'name'      : m.medicine_name,
                                                                   'unit'      : m.unit}
                                                      FROM medicines m WHERE m.medicine_id = i.medicine_id
                                                      WITH NOINSERT NOUPDATE NODELETE)}
                         FROM order_items i WHERE i.order_id = o.order_id
                         WITH INSERT UPDATE NODELETE ],
    'payments'       : [ SELECT JSON {'paymentId': p.payment_id,
                                      'method'   : p.method,
                                      'amount'   : p.amount,
                                      'paidAt'   : p.paid_at}
                         FROM payments p WHERE p.order_id = o.order_id
                         WITH INSERT NOUPDATE NODELETE ]
}
FROM orders o WITH INSERT UPDATE NODELETE;      -- hóa đơn không xóa: đổi orderStatus = CANCELLED

