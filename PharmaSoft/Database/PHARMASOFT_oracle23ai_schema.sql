CREATE TABLE prescriptions (
    prescription_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    customer_id     NUMBER NOT NULL,
    doctor_name     VARCHAR2(150 CHAR),
    doctor_id       NUMBER,
    image_url       VARCHAR2(500 CHAR),
    diagnosis       VARCHAR2(500 CHAR),
    issued_date     DATE,
    items           JSON,                                       -- danh sách thuốc trong đơn, dạng JSON
