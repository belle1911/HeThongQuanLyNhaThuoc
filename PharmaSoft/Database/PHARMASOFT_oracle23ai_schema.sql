/* ---------- A. TÀI KHOẢN & CON NGƯỜI ---------- */
CREATE TABLE roles (
    role_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    role_name    VARCHAR2(50 CHAR) NOT NULL CONSTRAINT uq_roles_name UNIQUE,   -- ADMIN, STAFF, CUSTOMER, DOCTOR
    description  VARCHAR2(255 CHAR)
);

CREATE TABLE users (
    user_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    role_id       NUMBER NOT NULL,
    full_name     VARCHAR2(150 CHAR) NOT NULL,
    username      VARCHAR2(80 CHAR)  NOT NULL CONSTRAINT uq_users_username UNIQUE,
    password_hash VARCHAR2(255 CHAR) NOT NULL,                 -- bcrypt/argon2, KHÔNG lưu plaintext
    email         VARCHAR2(150 CHAR) CONSTRAINT uq_users_email UNIQUE,   -- UNIQUE cho phép nhiều NULL
    phone         VARCHAR2(20 CHAR),
    avatar_url    VARCHAR2(500 CHAR),
    profile       JSON,                                        -- thông tin mở rộng linh hoạt
    is_active     NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT ck_users_active CHECK (is_active IN (0,1)),
    last_login_at TIMESTAMP,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at    TIMESTAMP,
    CONSTRAINT fk_users_roles FOREIGN KEY (role_id) REFERENCES roles(role_id)
);

CREATE TABLE employees (
    employee_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id       NUMBER NOT NULL CONSTRAINT uq_employees_user UNIQUE,
    employee_code VARCHAR2(30 CHAR) NOT NULL CONSTRAINT uq_employees_code UNIQUE,
    position      VARCHAR2(100 CHAR),
    hire_date     DATE,
    salary        NUMBER(18,2) CONSTRAINT ck_employees_salary CHECK (salary IS NULL OR salary >= 0),
    CONSTRAINT fk_employees_users FOREIGN KEY (user_id) REFERENCES users(user_id)
);

CREATE TABLE doctors (
    doctor_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id          NUMBER NOT NULL CONSTRAINT uq_doctors_user UNIQUE,
    specialty        VARCHAR2(150 CHAR),
    license_number   VARCHAR2(60 CHAR),
    years_experience NUMBER(3) CONSTRAINT ck_doctors_years CHECK (years_experience IS NULL OR years_experience >= 0),
    bio              VARCHAR2(1000 CHAR),
    is_available     NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT ck_doctors_avail CHECK (is_available IN (0,1)),
    CONSTRAINT fk_doctors_users FOREIGN KEY (user_id) REFERENCES users(user_id)
);

CREATE TABLE customers (
    customer_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id        NUMBER CONSTRAINT uq_customers_user UNIQUE,   -- NULL = khách vãng lai mua tại quầy
    full_name      VARCHAR2(150 CHAR) NOT NULL,
    phone          VARCHAR2(20 CHAR),
    email          VARCHAR2(150 CHAR),
    address        VARCHAR2(300 CHAR),
    date_of_birth  DATE,
    gender         CHAR(1) CONSTRAINT ck_customers_gender CHECK (gender IN ('M','F','O')),
    loyalty_points NUMBER(10) DEFAULT 0 NOT NULL CONSTRAINT ck_customers_points CHECK (loyalty_points >= 0),
    preferences    JSON,                                          -- dị ứng, thuốc hay mua, ghi chú...
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_customers_users FOREIGN KEY (user_id) REFERENCES users(user_id)
);
CREATE INDEX ix_customers_phone ON customers(phone);

/* ---------- B. DANH MỤC ---------- */
CREATE TABLE categories (
    category_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    parent_category_id NUMBER,
    category_name      VARCHAR2(120 CHAR) NOT NULL CONSTRAINT uq_categories_name UNIQUE,
    description        VARCHAR2(500 CHAR),
    is_active          NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT ck_categories_active CHECK (is_active IN (0,1)),
    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_category_id) REFERENCES categories(category_id)
);

CREATE TABLE manufacturers (
    manufacturer_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    manufacturer_name VARCHAR2(180 CHAR) NOT NULL CONSTRAINT uq_manufacturers_name UNIQUE,
    country           VARCHAR2(100 CHAR)
);

CREATE TABLE suppliers (
    supplier_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    supplier_name  VARCHAR2(180 CHAR) NOT NULL,
    contact_person VARCHAR2(150 CHAR),
    phone          VARCHAR2(20 CHAR),
    email          VARCHAR2(150 CHAR),
    address        VARCHAR2(300 CHAR),
    tax_code       VARCHAR2(30 CHAR),
    is_active      NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT ck_suppliers_active CHECK (is_active IN (0,1)),
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE medicines (
    medicine_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    category_id           NUMBER,
    manufacturer_id       NUMBER,
    default_supplier_id   NUMBER,
    medicine_code         VARCHAR2(40 CHAR)  NOT NULL CONSTRAINT uq_medicines_code UNIQUE,
    barcode               VARCHAR2(50 CHAR),
    medicine_name         VARCHAR2(200 CHAR) NOT NULL,
    unit                  VARCHAR2(40 CHAR)  NOT NULL,           -- hộp, vỉ, chai...
    requires_prescription NUMBER(1) DEFAULT 0 NOT NULL CONSTRAINT ck_med_rx CHECK (requires_prescription IN (0,1)),
    cost_price            NUMBER(18,2) DEFAULT 0 NOT NULL CONSTRAINT ck_med_cost CHECK (cost_price >= 0),
    sale_price            NUMBER(18,2) NOT NULL CONSTRAINT ck_med_sale CHECK (sale_price >= 0),
    min_stock_level       NUMBER(10) DEFAULT 0 NOT NULL CONSTRAINT ck_med_minstock CHECK (min_stock_level >= 0),
    image_url             VARCHAR2(500 CHAR),
    /* Thông tin linh hoạt dạng JSON: hoạt chất, hàm lượng, dạng bào chế, cách dùng, chống chỉ định, tags... */
    attributes            JSON,
    is_active             NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT ck_med_active CHECK (is_active IN (0,1)),
    created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at            TIMESTAMP,
    CONSTRAINT fk_med_categories    FOREIGN KEY (category_id)         REFERENCES categories(category_id),
    CONSTRAINT fk_med_manufacturers FOREIGN KEY (manufacturer_id)     REFERENCES manufacturers(manufacturer_id),
    CONSTRAINT fk_med_suppliers     FOREIGN KEY (default_supplier_id) REFERENCES suppliers(supplier_id),
    /* JSON Schema validation: attributes phải là object; ingredients/contraindications/tags phải là mảng */
    CONSTRAINT ck_med_attributes CHECK (attributes IS JSON VALIDATE '{
        "type": "object",
        "properties": {
            "activeIngredient": {"type": "string"},
            "strength":         {"type": "string"},
            "dosageForm":       {"type": "string"},
            "usage":            {"type": "string"},
            "contraindications":{"type": "array"},
            "tags":             {"type": "array"}
        }
    }')
);
CREATE INDEX ix_med_name     ON medicines(medicine_name);
CREATE INDEX ix_med_category ON medicines(category_id);
CREATE INDEX ix_med_barcode  ON medicines(barcode);

/* ---------- C. KHO (THEO LÔ) ---------- */
CREATE TABLE medicine_batches (
    batch_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    medicine_id       NUMBER NOT NULL,
    supplier_id       NUMBER,
    batch_number      VARCHAR2(60 CHAR) NOT NULL,
    manufacture_date  DATE,
    expiry_date       DATE NOT NULL,
    import_price      NUMBER(18,2) NOT NULL CONSTRAINT ck_batch_price CHECK (import_price >= 0),
    quantity_imported NUMBER(10) NOT NULL CONSTRAINT ck_batch_qin  CHECK (quantity_imported > 0),
    quantity_on_hand  NUMBER(10) NOT NULL CONSTRAINT ck_batch_qon  CHECK (quantity_on_hand >= 0),
    received_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_batch_medicines FOREIGN KEY (medicine_id) REFERENCES medicines(medicine_id),
    CONSTRAINT fk_batch_suppliers FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id),
    CONSTRAINT uq_batch_medicine_number UNIQUE (medicine_id, batch_number),
    CONSTRAINT ck_batch_onhand CHECK (quantity_on_hand <= quantity_imported)
);
CREATE INDEX ix_batch_fefo ON medicine_batches(medicine_id, expiry_date);      -- FEFO: hết hạn trước, xuất trước

CREATE TABLE stock_movements (                                  -- sổ kho: mọi biến động đều ghi
    movement_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    batch_id        NUMBER NOT NULL,
    movement_type   VARCHAR2(20 CHAR) NOT NULL
        CONSTRAINT ck_stock_type CHECK (movement_type IN ('PURCHASE','SALE','RETURN','ADJUSTMENT','EXPIRED','DAMAGED')),
    quantity_change NUMBER(10) NOT NULL CONSTRAINT ck_stock_qty CHECK (quantity_change <> 0),   -- + nhập, - xuất
    reference_type  VARCHAR2(30 CHAR),
    reference_id    NUMBER,
    note            VARCHAR2(300 CHAR),
    created_by      NUMBER,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_stock_batches FOREIGN KEY (batch_id)   REFERENCES medicine_batches(batch_id),
    CONSTRAINT fk_stock_users   FOREIGN KEY (created_by) REFERENCES users(user_id)
);
CREATE INDEX ix_stock_batch ON stock_movements(batch_id, created_at);

