CREATE OR REPLACE VIEW vw_medicine_stock AS
SELECT m.medicine_id, m.medicine_code, m.medicine_name, m.unit, m.sale_price, m.min_stock_level,
       NVL(SUM(CASE WHEN b.expiry_date >= TRUNC(SYSDATE) THEN b.quantity_on_hand END), 0) AS stock_quantity,
       MIN(CASE WHEN b.quantity_on_hand > 0 AND b.expiry_date >= TRUNC(SYSDATE) THEN b.expiry_date END) AS nearest_expiry_date
FROM medicines m
LEFT JOIN medicine_batches b ON b.medicine_id = m.medicine_id
WHERE m.is_active = 1
GROUP BY m.medicine_id, m.medicine_code, m.medicine_name, m.unit, m.sale_price, m.min_stock_level;

CREATE OR REPLACE VIEW vw_expiring_batches AS               -- lô hết hạn trong 90 ngày hoặc đã hết hạn
SELECT b.batch_id, m.medicine_code, m.medicine_name, b.batch_number, b.expiry_date, b.quantity_on_hand,
       TRUNC(b.expiry_date) - TRUNC(SYSDATE) AS days_left
FROM medicine_batches b
JOIN medicines m ON m.medicine_id = b.medicine_id
WHERE b.quantity_on_hand > 0 AND b.expiry_date <= TRUNC(SYSDATE) + 90;

CREATE OR REPLACE VIEW vw_low_stock AS
SELECT * FROM vw_medicine_stock WHERE stock_quantity <= min_stock_level;

CREATE OR REPLACE VIEW vw_daily_revenue AS
SELECT TRUNC(o.order_date) AS sale_date, COUNT(*) AS order_count, SUM(o.total_amount) AS revenue
FROM orders o
WHERE o.order_status = 'COMPLETED'
GROUP BY TRUNC(o.order_date);

CREATE OR REPLACE VIEW vw_top_selling_medicines AS
SELECT m.medicine_id, m.medicine_name,
       SUM(oi.quantity)                                   AS quantity_sold,
       SUM(oi.quantity * oi.unit_price)                   AS revenue,
       SUM(oi.quantity * (oi.unit_price - oi.unit_cost))  AS profit
FROM order_items oi
JOIN orders o    ON o.order_id = oi.order_id AND o.order_status = 'COMPLETED'
JOIN medicines m ON m.medicine_id = oi.medicine_id
GROUP BY m.medicine_id, m.medicine_name;

