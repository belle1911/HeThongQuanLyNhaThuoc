    batch_number      VARCHAR2(60 CHAR),
    expiry_date       DATE,
    quantity          NUMBER(10) NOT NULL CONSTRAINT ck_poi_qty  CHECK (quantity > 0),
    unit_cost         NUMBER(18,2) NOT NULL CONSTRAINT ck_poi_cost CHECK (unit_cost >= 0),
