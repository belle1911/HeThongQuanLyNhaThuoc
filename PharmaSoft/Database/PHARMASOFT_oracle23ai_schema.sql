/* =====================================================================
   3. JSON RELATIONAL DUALITY VIEWS
   Mỗi view là một "tài liệu JSON" gom nhiều bảng. Có thể GET/POST/PUT/DELETE như document;
   Oracle tự tách và ghi xuống từng bảng, giữ nguyên ràng buộc quan hệ + ACID.
   Chú thích ghi: WITH INSERT UPDATE DELETE  /  NOINSERT NOUPDATE NODELETE
   ===================================================================== */

-- 3.1 Thuốc: tài liệu gồm thông tin thuốc + danh mục/nhà sản xuất (chỉ đọc) + các lô hàng (ghi được)
CREATE OR REPLACE JSON RELATIONAL DUALITY VIEW medicine_dv AS
SELECT JSON {
    '_id'                 : m.medicine_id,
    'code'                : m.medicine_code,
    'barcode'             : m.barcode,
    'name'                : m.medicine_name,
    'unit'                : m.unit,
    'requiresPrescription': m.requires_prescription,
    'costPrice'           : m.cost_price,
    'salePrice'           : m.sale_price,
    'minStockLevel'       : m.min_stock_level,
    'imageUrl'            : m.image_url,
    'attributes'          : m.attributes,
    'isActive'            : m.is_active,
    'category'            : (SELECT JSON {'categoryId': c.category_id, 'categoryName': c.category_name}
                             FROM categories c WHERE c.category_id = m.category_id
                             WITH NOINSERT NOUPDATE NODELETE),
    'manufacturer'        : (SELECT JSON {'manufacturerId': f.manufacturer_id, 'manufacturerName': f.manufacturer_name}
                             FROM manufacturers f WHERE f.manufacturer_id = m.manufacturer_id
                             WITH NOINSERT NOUPDATE NODELETE),
    'batches'             : [ SELECT JSON {'batchId'        : b.batch_id,
                                           'batchNumber'    : b.batch_number,
                                           'expiryDate'     : b.expiry_date,
                                           'importPrice'    : b.import_price,
                                           'quantityImported': b.quantity_imported,
                                           'quantityOnHand' : b.quantity_on_hand}
                              FROM medicine_batches b WHERE b.medicine_id = m.medicine_id
                              WITH INSERT UPDATE NODELETE ]
}
FROM medicines m WITH INSERT UPDATE NODELETE;      -- không xóa cứng thuốc: dùng isActive = 0

